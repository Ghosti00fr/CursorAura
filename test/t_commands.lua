-- Tâche 6 : commande /aura et panneau
local M = dofile("test/mock.lua"); M.reset()
for _, f in ipairs({"Locales/enUS","Locales/frFR","Locales/esES","Core","Effects","Specs","Particles","Renderer","PvP","Crest","Bank","Options","Commands","Minimap"}) do dofile("CursorAura/"..f..".lua") end; CA = CursorAura
CA.Config:Init(); CA.Renderer:Init()
ok(SLASH_CURSORAURA1 == "/aura" and type(SlashCmdList.CURSORAURA) == "function", "/aura enregistrée")
CA.Commands:Run("trainee"); ok(CA.Config:Get("mode") == "trainee", "mode traînée")
CA.Commands:Run("trail");   ok(CA.Config:Get("mode") == "trainee", "nom anglais du mode")
CA.Commands:Run("seul"); CA.Renderer:OnUpdate(1/60); ok(CA.Renderer.mode == "seul", "Refresh appelé")
CA.Commands:Run("Fumée");   ok(CA.Config:Get("choice") == "fumee", "accent + majuscule")
CA.Commands:Run("FEU");     ok(CA.Config:Get("choice") == "feu", "majuscules")
CA.Commands:Run("smoke");   ok(CA.Config:Get("choice") == "fumee", "nom anglais")
CA.Commands:Run("relampago"); ok(CA.Config:Get("choice") == "eclairs", "nom espagnol sans accent")
CA.Commands:Run("  Relámpago "); ok(CA.Config:Get("choice") == "eclairs", "espaces + accent espagnol")
CA.Commands:Run("retribution"); ok(CA.Config:Get("choice") == "vindicte", "vindicte (EN)")
CA.Commands:Run("Protección"); ok(CA.Config:Get("choice") == "protection", "protection (ES)")
CA.Commands:Run("auto");    ok(CA.Config:Get("choice") == "auto", "auto")
M.printed = {}; CA.Commands:Run("lave"); ok(#M.printed > 0 and CA.Config:Get("choice") == "auto", "inconnu -> aide, rien changé")
M.classFile = "SHAMAN"; M.specIndex = 1; M.specs = { [1] = { 262, "Élémentaire" } }
M.printed = {}; CA.Commands:Run("debug")
local all = table.concat(M.printed, "\n")
ok(all:find("SHAMAN") and all:find("262") and all:find("eclairs"), "debug : classe, specID, effet")
M.specIndex = nil; M.printed = {}; CA.Commands:Run("debug")
ok(table.concat(M.printed, "\n"):find("nil"), "debug : valeurs absentes = nil")
ok(table.concat(M.printed, "\n"):find("tabs: ", 1, true), "debug : points par onglet")
CA.Commands:Run(""); ok(CursorAuraOptions and CursorAuraOptions:IsShown(), "panneau ouvert")
ok(UISpecialFrames[1] == "CursorAuraOptions", "Échap ferme le panneau")
CA.Commands:Run(""); ok(not CursorAuraOptions:IsShown(), "panneau refermé")
CA.Options.effectButtons.givre.scripts.OnClick(CA.Options.effectButtons.givre)
ok(CA.Config:Get("choice") == "givre", "panneau : clic effet")
CA.Options.modeButtons.aura.scripts.OnClick(CA.Options.modeButtons.aura)
ok(CA.Config:Get("mode") == "aura", "panneau : clic mode")
CA.Options.autoButton.scripts.OnClick(CA.Options.autoButton)
ok(CA.Config:Get("choice") == "auto", "panneau : clic auto")
CA.Commands:Run("Traînée"); ok(CA.Config:Get("mode") == "trainee", "î reconnu")
CA.Commands:Run("seul"); CA.Commands:Run("TRAÎNÉE"); ok(CA.Config:Get("mode") == "trainee", "Î majuscule reconnu")
CA.Commands:Run("curseur seul"); ok(CA.Config:Get("mode") == "seul", "libellé FR du panneau")
CA.Commands:Run("trail"); CA.Commands:Run("Cursor only"); ok(CA.Config:Get("mode") == "seul", "libellé EN du panneau")
CA.Commands:Run("trail"); CA.Commands:Run("Solo cursor"); ok(CA.Config:Get("mode") == "seul", "libellé ES du panneau")
